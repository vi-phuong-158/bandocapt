'use strict';

const SAFE_GATEWAY_CODES = new Set([
    'EMAIL_NOT_AUTHORIZED_FOR_UNIT', 'CREATE_TARGET_RECORD_ID_NOT_ALLOWED', 'TARGET_RECORD_ID_NOT_FOUND',
    'TARGET_RECORD_UNIT_MISMATCH', 'IMAGE_ENCODING_INVALID', 'IMAGE_TYPE_NOT_ALLOWED', 'IMAGE_TOO_LARGE',
    'IDEMPOTENCY_KEY_REUSED_WITH_DIFFERENT_PAYLOAD', 'TARGET_RECORD_ID_REQUIRED', 'UNIT_CODE_REQUIRED',
    'IMAGE_REQUIRED', 'SERVICES_MISSING', 'ADDRESS_MISSING', 'LOCATION_NAME_MISSING',
    'COORDINATE_NEEDS_REVIEW', 'COORDINATE_INVALID_LINK', 'COORDINATE_OUTSIDE_PHU_THO',
]);

const SAFE_LOCAL_CODES = new Set([
    'STAFF_REQUEST_FAILED', 'STAFF_ORIGIN_REJECTED', 'CSRF_TOKEN_MISSING', 'CSRF_TOKEN_INVALID',
    'STAFF_NOT_AUTHORIZED', 'STAFF_ACCESS_REVOKED', 'STAFF_SESSION_INVALID', 'GOOGLE_TOKEN_INVALID',
    'STAFF_SESSION_CONFIG_INVALID', 'STAFF_AUTH_CONFIG_INVALID', 'STAFF_GATEWAY_CONFIG_INVALID',
    'STAFF_GATEWAY_UNAVAILABLE', 'STAFF_OPERATIONAL_BASELINE_NOT_READY', 'STAFF_GATEWAY_INVALID_RESPONSE',
    'STAFF_GATEWAY_REJECTED', 'STALE_PUBLIC_SNAPSHOT', 'STAFF_IMAGE_TOO_LARGE', 'STAFF_REQUEST_TOO_LARGE',
    'STAFF_PUBLIC_SOURCE_UNAVAILABLE',
    'INVALID_BODY', 'STAFF_REQUEST_INVALID', 'METHOD_NOT_ALLOWED', 'OPERATION_ID_INVALID', 'IMAGE_ENCODING_INVALID',
    'EVENT_TYPE_NOT_ALLOWED', 'TARGET_RECORD_ID_INVALID', 'SNAPSHOT_HASH_INVALID', 'REQUEST_TYPE_INVALID',
    'CREATE_SNAPSHOT_HASH_NOT_ALLOWED', 'SNAPSHOT_HASH_REQUIRED', 'MAPS_RESOLVE_UNAVAILABLE',
]);

const STATUS_BY_CODE = new Map([
    ['STAFF_ORIGIN_REJECTED', 403], ['CSRF_TOKEN_MISSING', 403], ['CSRF_TOKEN_INVALID', 403],
    ['STAFF_NOT_AUTHORIZED', 403], ['STAFF_ACCESS_REVOKED', 403], ['TARGET_RECORD_UNIT_MISMATCH', 403],
    ['EMAIL_NOT_AUTHORIZED_FOR_UNIT', 403],
    ['STAFF_SESSION_INVALID', 401], ['GOOGLE_TOKEN_INVALID', 401], ['STAFF_SESSION_CONFIG_INVALID', 503],
    ['STAFF_AUTH_CONFIG_INVALID', 503], ['STAFF_GATEWAY_CONFIG_INVALID', 503], ['STAFF_GATEWAY_UNAVAILABLE', 503],
    ['STAFF_OPERATIONAL_BASELINE_NOT_READY', 503], ['STAFF_PUBLIC_SOURCE_UNAVAILABLE', 503], ['STAFF_GATEWAY_INVALID_RESPONSE', 502],
    ['STAFF_GATEWAY_REJECTED', 502], ['STALE_PUBLIC_SNAPSHOT', 409], ['IDEMPOTENCY_KEY_REUSED_WITH_DIFFERENT_PAYLOAD', 409],
    ['STAFF_REQUEST_INVALID', 400],
    ['STAFF_IMAGE_TOO_LARGE', 413], ['STAFF_REQUEST_TOO_LARGE', 413],
    ['MAPS_RESOLVE_UNAVAILABLE', 503],
]);

function safeGatewayCode(code) {
    return SAFE_GATEWAY_CODES.has(code) ? code : 'STAFF_GATEWAY_REJECTED';
}

function statusForError(code) {
    if (STATUS_BY_CODE.has(code)) return STATUS_BY_CODE.get(code);
    if (/^(INVALID_|MISSING_|REQUEST_|OPERATION_|UNIT_|CREATE_|TARGET_|IMAGE_|SERVICES_|ADDRESS_|LOCATION_|COORDINATE_)/.test(code)) return 400;
    return 500;
}

function publicErrorCode(error) {
    const code = String(error?.code || error?.message || 'STAFF_REQUEST_FAILED');
    if (SAFE_LOCAL_CODES.has(code)) return code;
    if (SAFE_GATEWAY_CODES.has(code)) return code;
    return 'STAFF_REQUEST_FAILED';
}

function sendStaffError(res, error) {
    const code = publicErrorCode(error);
    return res.status(statusForError(code)).json({ ok: false, error: { code } });
}

function sendStaffData(res, data, status = 200) {
    res.setHeader('Cache-Control', 'no-store');
    return res.status(status).json({ ok: true, data });
}

module.exports = { SAFE_GATEWAY_CODES, statusForError, safeGatewayCode, publicErrorCode, sendStaffError, sendStaffData };
